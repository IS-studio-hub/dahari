def parse_excel_rows(rows):
    projects = []
    section_counts = {}
    seen_slugs = set()

    for excel_row in rows[1:]:
        cat = clean_text(excel_row[0] if len(excel_row) > 0 else "")
        section = CATEGORY_MAP.get(cat)
        if not section:
            continue

        row = {
            "category": cat,
            "detail": clean_text(excel_row[1] if len(excel_row) > 1 else ""),
            "address": clean_text(excel_row[2] if len(excel_row) > 2 else ""),
            "floor": clean_text(excel_row[3] if len(excel_row) > 3 else ""),
            "built": excel_row[4] if len(excel_row) > 4 else "",
            "area": excel_row[5] if len(excel_row) > 5 else "",
            "long_desc": excel_row[6] if len(excel_row) > 6 else "",
            "short_desc": excel_row[7] if len(excel_row) > 7 else "",
        }
        if not row_has_content(row):
            continue

        section_counts[section] = section_counts.get(section, 0) + 1
        idx = section_counts[section]
        prefix = SECTION_META[section]["prefix"]

        base_slug = make_slug(section, idx, row).replace(".html", "")
        slug = base_slug
        if slug in seen_slugs:
            slug = f"{base_slug}-{idx:02d}"
        seen_slugs.add(slug)
        filename = f"{slug}.html"

        title = project_title(row)
        short_desc = (row["short_desc"] or "").strip()
        long_desc = (row["long_desc"] or "").strip()
        body_html = format_body_html(long_desc, short_desc)
        tagline = row["detail"] or first_line(short_desc) or title
        built = clean_text(row["built"])
        plot_area = clean_text(row["area"])
        card_area = area_text(row["built"], row["area"])
        short_desc = CARD_DESC_OVERRIDES.get(filename, short_desc)
        page_override = PRODUCT_PAGE_OVERRIDES.get(filename, {})
        if "title" in page_override:
            title = page_override["title"]
        if "tagline" in page_override:
            tagline = page_override["tagline"]
        if "long_desc" in page_override:
            long_desc = page_override["long_desc"]
            body_html = format_body_html(long_desc, short_desc)
        floor = row["floor"]
        if "floor" in page_override:
            floor = page_override["floor"]
        gallery_folder = GALLERY_FOLDER_SOURCES.get(filename)
        if gallery_folder:
            gallery_media = resolve_folder_gallery(gallery_folder)
            images = gallery_image_srcs(gallery_media)
        else:
            gallery_media = None
            images = resolve_project_images(section, row, title)
            card_override = CARD_IMAGE_OVERRIDES.get(filename)
            if card_override:
                override_href = asset_href(card_override)
                images = [override_href] + [img for img in images if img != override_href]

        projects.append(
            {
                "slug": slug.replace(".html", ""),
                "section": section,
                "title": title,
                "tagline": tagline,
                "short_desc": short_desc,
                "long_desc": long_desc,
                "body_html": body_html,
                "address": row["address"] or title,
                "built": built,
                "plot_area": plot_area,
                "area": card_area,
                "floor": floor,
                "images": images,
                "filename": filename,
                "hide_plot_meta": page_override.get("hide_plot_meta", False),
                "gallery_folder": gallery_folder,
                "gallery_media": gallery_media,
            }
        )

    return projects


