def _collect_from(rel):
    """Return image files under a RealEstate folder (recursive) or a single file.

    Curated top-level renders/photos come first (shallowest depth), drone
    "stills" in nested folders last; "small" variants are always last. Video
    folders are skipped.
    """
    base = REAL_ESTATE / rel
    if base.is_file():
        return [base] if base.suffix.lower() in IMAGE_EXT else []
    if not base.is_dir():
        return []

    items = []
    for p in base.rglob("*"):
        if not p.is_file() or p.suffix.lower() not in IMAGE_EXT:
            continue
        if any(hint in part for part in p.parts for hint in VIDEO_DIR_HINTS):
            continue
        depth = len(p.relative_to(base).parts) - 1
        items.append((depth, p))

    def sort_key(item):
        depth, path = item
        is_small = 1 if "small" in path.stem.lower() else 0
        return (is_small, depth, _natural_sort_key(path))

    items.sort(key=sort_key)
    return [p for _, p in items]


def _collect_folder_media(folder):
    """Image and video files in a gallery folder (non-recursive).

    Mixed in one list by natural filename so photos and videos share a grid.
    When WebP versions exist, skip raster originals so galleries aren't duplicated.
    """
    if not folder.is_dir():
        return []
    items = [
        p
        for p in folder.iterdir()
        if p.is_file()
        and p.suffix.lower() in MEDIA_EXT
        and not p.name.startswith(".")
        and p.name != "manifest.json"
    ]
    has_webp = any(p.suffix.lower() == ".webp" for p in items)
    if has_webp:
        items = [
            p
            for p in items
            if p.suffix.lower() in VIDEO_EXT or p.suffix.lower() == ".webp"
        ]
    items.sort(key=_natural_sort_key)
    return items


